export interface MenuFilterOptions {
  isRegistered(command: string): boolean;
  /** Development flag: keep unregistered items (they render greyed out). */
  showUnimplemented: boolean;
}

/** Removes unavailable items, empty submenus and redundant separators. */
export function visibleEntries(entries: readonly MenuEntry[], options: MenuFilterOptions): MenuEntry[] {
  const kept: MenuEntry[] = [];
  for (const entry of entries) {
    if (entry.kind === 'item') {
      if (options.showUnimplemented || options.isRegistered(entry.command)) kept.push(entry);
    } else if (entry.kind === 'submenu') {
      const items = visibleEntries(entry.items, options);
      if (items.some((e) => e.kind !== 'separator')) kept.push({ ...entry, items });
    } else {
      kept.push(entry);
    }
  }
  // Collapse separators: none at the start or end, never two in a row.
  const result: MenuEntry[] = [];
  for (const entry of kept) {
    if (entry.kind === 'separator' && (result.length === 0 || result.at(-1)!.kind === 'separator')) continue;
    result.push(entry);
  }
  if (result.at(-1)?.kind === 'separator') result.pop();
  return result;
}
