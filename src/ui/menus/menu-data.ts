/**
 * The menu bar: the reference app's menu structure and grouping (CLAUDE.md §1),
 * with our own wording. Items point at app command ids; items whose command is not
 * registered are hidden (or shown greyed out with the development flag), so the
 * menus only ever offer what works.
 */

export type MenuEntry =
  | { kind: 'item'; command: string; label: string }
  | { kind: 'submenu'; label: string; items: MenuEntry[] }
  | { kind: 'separator' }
  /** Filled at runtime (e.g. the list of open documents in the Window menu). */
  | { kind: 'dynamic'; source: 'open-documents' };

export interface TopMenu {
  id: string;
  label: string;
  items: MenuEntry[];
}

const item = (command: string, label: string): MenuEntry => ({ kind: 'item', command, label });
const sub = (label: string, items: MenuEntry[]): MenuEntry => ({ kind: 'submenu', label, items });
const sep: MenuEntry = { kind: 'separator' };

